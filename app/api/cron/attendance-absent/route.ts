export const runtime = "nodejs";

import { NextRequest, NextResponse } from "next/server";
import prisma from "@/lib/prisma";
import { getJakartaDayKey, getJakartaDayRange } from "@/lib/helper/date";
import { isAuthorizedCron } from "@/lib/auth/cron";
import { getAttendanceCronDay } from "@/lib/helper/attendance-cron";
import { getScheduledWorkDays } from "@/lib/helper/work-schedule";
import { getNationalHolidayByDate } from "@/lib/helper/holiday";
import {
  AUTO_ABSENT_NOTE,
  AUTO_SUBMISSION_ATTENDANCE_NOTE,
} from "@/lib/helper/submission-attendance";

const AUTO_OVERTIME_ATTENDANCE_NOTE =
  "Auto generated by cron from overtime";

const JAKARTA_UTC_OFFSET_HOURS = 7;
const WEEKDAY_MAP = [
  "SUNDAY",
  "MONDAY",
  "TUESDAY",
  "WEDNESDAY",
  "THURSDAY",
  "FRIDAY",
  "SATURDAY",
] as const;

function getDurationString(start: Date, end: Date) {
  const totalMinutes = Math.max(
    0,
    Math.floor((end.getTime() - start.getTime()) / (1000 * 60)),
  );
  const hours = Math.floor(totalMinutes / 60);
  const minutes = totalMinutes % 60;
  return `${String(hours).padStart(2, "0")}:${String(minutes).padStart(2, "0")}`;
}

export async function GET(req: NextRequest) {
  try {
    if (!isAuthorizedCron(req)) {
      return NextResponse.json({ message: "Unauthorized" }, { status: 401 });
    }

    let targetDay: Date;
    try { targetDay = getAttendanceCronDay(req.nextUrl.searchParams.get("date")); }
    catch { return NextResponse.json({ message: "Tanggal cron tidak valid atau belum lewat" }, { status: 400 }); }
    const dryRun = req.nextUrl.searchParams.get("dryRun") === "true";
    const now = new Date();
    const { startUtc, endUtc } = getJakartaDayRange(targetDay);
    const targetDayCode = WEEKDAY_MAP[
      new Date(
        startUtc.getTime() + JAKARTA_UTC_OFFSET_HOURS * 60 * 60 * 1000,
      ).getUTCDay()
    ];
    const attendanceDay = getJakartaDayKey(startUtc);
    const targetDateKey = attendanceDay.toISOString().slice(0, 10);
    const nationalHoliday = await getNationalHolidayByDate(targetDateKey);

    const eligibleUsers = await prisma.user.findMany({
      where: {
        status: "active",
        deletedAt: null,
        AND: [
          {
            OR: [{ joinDate: null }, { joinDate: { lte: endUtc } }],
          },
          {
            OR: [
              { tenantId: null },
              {
                tenant: {
                  isActive: true,
                },
              },
            ],
          },
        ],
      },
      select: {
        id: true,
        tenantId: true,
        branchId: true,
        branch: { select: { scheduleType: true, isActive: true } },
      },
    });

    if (eligibleUsers.length === 0) {
      return NextResponse.json({
        message: "Attendance absent job completed",
        created: 0,
        targetDateStart: startUtc.toISOString(),
        targetDateEnd: endUtc.toISOString(),
      });
    }

    const overtimeRecords = await prisma.overtime.findMany({
      where: {
        userId: {
          in: eligibleUsers.map((user) => user.id),
        },
        overtimeDate: attendanceDay,
        endTime: { not: null },
        status: "APPROVED",
      },
      select: {
        id: true,
        userId: true,
        tenantId: true,
        startTime: true,
        endTime: true,
      },
      orderBy: [{ endTime: "desc" }, { startTime: "asc" }],
    });

    const overtimeByUserId = new Map<
      string,
      {
        id: string;
        tenantId: string | null;
        startTime: Date | null;
        endTime: Date | null;
      }
    >();
    for (const overtime of overtimeRecords) {
      if (!overtimeByUserId.has(overtime.userId)) {
        overtimeByUserId.set(overtime.userId, overtime);
      }
    }

    if (nationalHoliday && overtimeByUserId.size === 0) {
      return NextResponse.json({
        message: "Attendance absent job skipped because target date is a national holiday",
        created: 0,
        updated: 0,
        targetDateStart: startUtc.toISOString(),
        targetDateEnd: endUtc.toISOString(),
        targetDayCode,
        skippedByNationalHoliday: true,
        holidayName: nationalHoliday.name,
        holidayDate: nationalHoliday.date,
      });
    }

    const nextDay = new Date(targetDay);
    nextDay.setUTCDate(nextDay.getUTCDate() + 1);
    const scheduledEndByUser = new Map<string, Date>();
    for (const user of eligibleUsers) {
      if (!user.branchId || !user.branch?.isActive) continue;
      const schedules = await getScheduledWorkDays(prisma, user.id, { gte: targetDay, lt: nextDay });
      const schedule = schedules.find((day) => day.workDate.getTime() === targetDay.getTime());
      if (schedule && schedule.endAt <= now) scheduledEndByUser.set(user.id, schedule.endAt);
    }
    const usersToProcess = eligibleUsers.filter((user) =>
      overtimeByUserId.has(user.id) || scheduledEndByUser.has(user.id),
    );

    if (usersToProcess.length === 0) {
      return NextResponse.json({
        message: "Attendance absent job completed",
        created: 0,
        targetDateStart: startUtc.toISOString(),
        targetDateEnd: endUtc.toISOString(),
        checkedUsers: eligibleUsers.length,
        skippedByWorkingDay: eligibleUsers.length,
        targetDayCode,
      });
    }

    const existingAttendances = await prisma.attendance.findMany({
      where: {
        attendanceDay,
        userId: {
          in: usersToProcess.map((u) => u.id),
        },
      },
      select: {
        id: true,
        userId: true,
        checkIn: true,
        checkOut: true,
        status: true,
        notes: true,
        updatedAt: true,
      },
    });

    const existingUserIds = new Set(existingAttendances.map((a) => a.userId));
    const usersWithoutAttendance = usersToProcess.filter((u) => !existingUserIds.has(u.id));

    const approvedSubmissions = usersWithoutAttendance.length
      ? await prisma.submission.findMany({
          where: {
            status: "APPROVED",
            deletedAt: null,
            userId: {
              in: usersWithoutAttendance.map((user) => user.id),
            },
            startDate: {
              lte: endUtc,
            },
            endDate: {
              gte: startUtc,
            },
          },
          select: {
            userId: true,
            approvedAt: true,
            createdAt: true,
            submissionType: {
              select: {
                name: true,
              },
            },
          },
          orderBy: [
            { approvedAt: "desc" },
            { createdAt: "desc" },
          ],
        })
      : [];

    const submissionTypeByUserId = new Map<string, string>();
    for (const submission of approvedSubmissions) {
      if (!submissionTypeByUserId.has(submission.userId)) {
        submissionTypeByUserId.set(submission.userId, submission.submissionType.name);
      }
    }

    const attendanceToCreate = usersWithoutAttendance
      .filter((user) => !nationalHoliday || overtimeByUserId.has(user.id))
      .map((u) => {
        const overtime = overtimeByUserId.get(u.id);
        if (overtime?.startTime && overtime.endTime) {
          return {
            userId: u.id,
            tenantId: u.tenantId ?? null,
            branchId: u.branchId ?? null,
            date: overtime.startTime,
            attendanceDay,
            checkIn: overtime.startTime,
            checkOut: overtime.endTime,
            status: "Lembur",
            notes: AUTO_OVERTIME_ATTENDANCE_NOTE,
            workHours: getDurationString(overtime.startTime, overtime.endTime),
          };
        }

        return {
        userId: u.id,
        tenantId: u.tenantId ?? null,
        branchId: u.branchId ?? null,
        date: startUtc,
        attendanceDay,
        scheduledEndAt: scheduledEndByUser.get(u.id) ?? null,
        status: submissionTypeByUserId.get(u.id) ?? "Absent",
        notes: submissionTypeByUserId.has(u.id)
          ? AUTO_SUBMISSION_ATTENDANCE_NOTE
          : AUTO_ABSENT_NOTE,
        workHours: "00:00",
        };
      });

    const attendancesToUpdate: ReturnType<typeof prisma.attendance.updateMany>[] = [];

    existingAttendances.forEach((attendance) => {
        const overtime = overtimeByUserId.get(attendance.userId);
        if (!overtime?.startTime || !overtime.endTime) {
          return;
        }

        const nextCheckIn = attendance.checkIn
          ? new Date(Math.min(new Date(attendance.checkIn).getTime(), overtime.startTime.getTime()))
          : overtime.startTime;
        const nextCheckOut = attendance.checkOut
          ? new Date(Math.max(new Date(attendance.checkOut).getTime(), overtime.endTime.getTime()))
          : overtime.endTime;

        attendancesToUpdate.push(prisma.attendance.updateMany({
          where: { id: attendance.id, updatedAt: attendance.updatedAt },
          data: {
            date: nextCheckIn,
            checkIn: nextCheckIn,
            checkOut: nextCheckOut,
            status: "Lembur",
            notes: attendance.notes || AUTO_OVERTIME_ATTENDANCE_NOTE,
            workHours: getDurationString(nextCheckIn, nextCheckOut),
          },
        }));
      });

    let created = 0;
    if (!dryRun && attendanceToCreate.length > 0) {
      const result = await prisma.attendance.createMany({
        data: attendanceToCreate,
        skipDuplicates: true,
      });
      created = result.count;
    }

    let updated = 0;
    if (!dryRun && attendancesToUpdate.length > 0) {
      const results = await prisma.$transaction(attendancesToUpdate);
      updated = results.reduce((total, result) => total + result.count, 0);
    }

    return NextResponse.json({
      message: "Attendance absent job completed",
      dryRun,
      eligibleToCreate: attendanceToCreate.length,
      eligibleToUpdate: attendancesToUpdate.length,
      created,
      updated,
      targetDateStart: startUtc.toISOString(),
      targetDateEnd: endUtc.toISOString(),
      checkedUsers: usersToProcess.length,
      skippedByWorkingDay: eligibleUsers.length - usersToProcess.length,
      targetDayCode,
    });
  } catch (error) {
    console.error("CRON ATTENDANCE ABSENT ERROR:", error);
    return NextResponse.json(
      { message: "Failed to run attendance absent job" },
      { status: 500 },
    );
  }
}
